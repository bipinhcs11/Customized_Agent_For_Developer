# Public entry point
# ─────────────────────────────────────────────────────────────────────────────

def crawl(repo_root: str | Path, *, extra_excludes: set | None = None,
          include_tests: bool = True) -> CrawlIndex:
    """Walk the repo and return a CrawlIndex. Pure local — no AI calls."""
    repo_root = Path(repo_root).resolve()
    if not repo_root.is_dir():
        raise ValueError(f"Not a directory: {repo_root}")

    extra_excludes = set(extra_excludes or [])
    warnings: list = []
    java_classes: list = []
    xml_signals: list = []
    config_signals: list = []
    sql_signals: list = []
    shell_signals: list = []
    skipped = 0

    for path in _iter_files(repo_root, extra_excludes):
        suffix = path.suffix.lower()
        try:
            if suffix == ".java":
                results, warn = parse_java_file(path, repo_root)
                if warn:
                    warnings.append(warn)
                for jc in results:
                    if "test" in jc.flags and not include_tests:
                        skipped += 1
                        continue
                    java_classes.append(jc)
            elif suffix == ".xml":
                result, warn = parse_xml_file(path, repo_root)
                if warn:
                    warnings.append(warn)
                if result is not None:
                    xml_signals.append(result)
            elif suffix in {".properties", ".yml", ".yaml"}:
                result, warn = parse_config_file(path, repo_root)
                if warn:
                    warnings.append(warn)
                if result is not None:
                    config_signals.append(result)
            elif suffix in {".sql", ".ddl"}:
                result, warn = parse_sql_file(path, repo_root)
                if warn:
                    warnings.append(warn)
                if result is not None:
                    sql_signals.append(result)
            elif suffix in {".sh", ".bash"}:
                result, warn = parse_shell_file(path, repo_root)
                if warn:
                    warnings.append(warn)
                if result is not None:
                    shell_signals.append(result)
            else:
                skipped += 1
        except Exception as e:  # pragma: no cover — defensive
            warnings.append(f"unexpected-error: {path} ({type(e).__name__}: {e})")
            skipped += 1

    total_loc = sum(jc.line_count for jc in java_classes)
    framework = _detect_framework(java_classes, xml_signals)
    build_system = _detect_build_system(repo_root)
    java_version = _detect_java_version(repo_root)

    project_type = _infer_project_type(java_classes, xml_signals, sql_signals, shell_signals, framework)

    if not java_classes and not xml_signals and not sql_signals:
        warnings.append("zero-source-files: no Java/XML/SQL found under repo root")

    return CrawlIndex(
        schema_version=SCHEMA_VERSION,
        scan={
            "root": str(repo_root),
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "tool_version": TOOL_VERSION,
        },
        stats={
            "java_classes": len(java_classes),
            "xml_files": len(xml_signals),
            "config_files": len(config_signals),
            "sql_files": len(sql_signals),
            "shell_files": len(shell_signals),
            "skipped_files": skipped,
            "total_java_loc": total_loc,
            "framework": framework,
            "build_system": build_system,
            "java_version": java_version,
            "project_type": project_type,
        },
        warnings=warnings,
        java_classes=java_classes,
        xml_signals=xml_signals,
        config_signals=config_signals,
        sql_signals=sql_signals,
        shell_signals=shell_signals,
    )


def _infer_project_type(java_classes: list, xml_signals: list,
                        sql_signals: list, shell_signals: list, framework: str) -> str:
    has_rest = any("RestController" in jc.annotations or "Controller" in jc.annotations
                   or "Path" in jc.annotations for jc in java_classes)
    has_batch = any("EnableBatchProcessing" in jc.annotations or "Job" in jc.annotations
                    for jc in java_classes) or any(
        s.xml_type == "spring_batch" for s in xml_signals
    )
    has_scheduled = any("Scheduled" in jc.annotations for jc in java_classes) or any(
        s.xml_type == "quartz" for s in xml_signals
    )
    has_stored_procs = any(s.sql_kind in {"stored_proc", "mixed"} for s in sql_signals)
    has_shell_orchestration = any(s.java_invocations or s.java_jars for s in shell_signals)

    if has_rest and (has_batch or has_scheduled):
        return "Hybrid"
    if has_rest:
        return "REST API"
    if has_batch:
        return "Batch Job"
    if has_scheduled:
        return "Scheduled"
    if has_stored_procs and has_shell_orchestration:
        return "Legacy (stored-proc + shell)"
    if has_stored_procs:
        return "Stored-Procedure Driven"
    if framework == "Raw Servlet" or any(s.xml_type == "web_xml" for s in xml_signals):
        return "Monolith Module"
    return "Unknown"


# ─────────────────────────────────────────────────────────────────────────────
# CLI-style invocation
# ─────────────────────────────────────────────────────────────────────────────

def _to_json(index: CrawlIndex) -> str:
    return json.dumps(asdict(index), indent=2, ensure_ascii=False, default=str)


def _main(argv: list) -> int:
    if len(argv) < 2:
        print("Usage: python -m skill_generator.crawler <repo-root> [--output FILE]", file=sys.stderr)
        return 2
    repo_root = argv[1]
    output = None
    if "--output" in argv:
        i = argv.index("--output")
        output = argv[i + 1] if i + 1 < len(argv) else None
    index = crawl(repo_root)
    out = _to_json(index)
    if output:
        Path(output).write_text(out)
    else:
        print(out)
    return 0


if __name__ == "__main__":
    sys.exit(_main(sys.argv))
