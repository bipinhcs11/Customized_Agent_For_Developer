# ─────────────────────────────────────────────────────────────────────────────
# Regex parsers (lightweight — no full Java AST library)
# ─────────────────────────────────────────────────────────────────────────────

RE_PACKAGE = re.compile(r"^\s*package\s+([\w.]+)\s*;", re.MULTILINE)
RE_IMPORT = re.compile(r"^\s*import\s+(?:static\s+)?([\w.]+(?:\.\*)?)\s*;", re.MULTILINE)
RE_TYPE_DECL = re.compile(
    r"^\s*(?:public|private|protected)?\s*"
    r"(?:(?:abstract|final|static|sealed|non-sealed)\s+)*"
    r"(class|interface|enum|record)\s+"
    r"(\w+)"
    r"(?:\s*<[^>]+>)?"
    r"(?:\s+extends\s+([\w.<>,\s]+?))?"
    r"(?:\s+implements\s+([\w.<>,\s?]+?))?"
    r"\s*[\{(]",
    re.MULTILINE,
)
RE_ANNOTATION = re.compile(r"^\s*@(\w+)", re.MULTILINE)
RE_METHOD = re.compile(
    r"^\s*(?:public|private|protected)\s+"
    r"(?:(?:static|final|abstract|synchronized|default|native)\s+)*"
    r"(?:<[^>]+>\s+)?"
    r"[\w<>,\[\]?.\s]+?\s+"
    r"(\w+)\s*\("
    r"[^)]*\)"
    r"(?:\s*throws\s+[\w.,\s]+)?"
    r"\s*[\{;]",
    re.MULTILINE,
)
RE_DEPRECATED_ANN = re.compile(r"@Deprecated\b")
RE_DEPRECATED_DOC = re.compile(r"\*\s*@deprecated", re.IGNORECASE)
RE_TEST_FILENAME = re.compile(r"(Test|Tests|IT)\.java$")

# Strip line/block comments so they don't pollute method/annotation extraction.
RE_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
RE_LINE_COMMENT = re.compile(r"//[^\n]*")
RE_STRING_LITERAL = re.compile(r'"(?:[^"\\]|\\.)*"')


