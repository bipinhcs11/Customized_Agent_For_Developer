@dataclass
class JavaClass:
    file_path: str
    package: str | None
    class_name: str
    type: str  # class | interface | enum | record
    annotations: list = field(default_factory=list)
    method_names: list = field(default_factory=list)
    extends: str | None = None
    implements: list = field(default_factory=list)
    import_tail_tokens: list = field(default_factory=list)
    line_count: int = 0
    flags: list = field(default_factory=list)


@dataclass
class XmlSignal:
    file_path: str
    xml_type: str   # web_xml | struts_config | spring_context | hibernate_cfg | hbm | persistence | quartz | unknown
    signals: list = field(default_factory=list)


@dataclass
class ConfigSignal:
    file_path: str
    config_type: str   # properties | yaml
    key_prefixes: list = field(default_factory=list)


@dataclass
class SqlSignal:
    file_path: str
    sql_kind: str       # migration | stored_proc | ddl | mixed
    procedures: list = field(default_factory=list)   # CREATE PROCEDURE / FUNCTION names
    tables: list = field(default_factory=list)       # CREATE TABLE names
    views: list = field(default_factory=list)        # CREATE VIEW names
    altered_tables: list = field(default_factory=list)
    flags: list = field(default_factory=list)        # flyway_migration | liquibase | callable_from_java


@dataclass
class ShellSignal:
    file_path: str
    java_invocations: list = field(default_factory=list)   # FQNs of Java classes invoked
    java_jars: list = field(default_factory=list)          # JAR names invoked
    sql_invocations: list = field(default_factory=list)    # psql / mysql / sqlplus + .sql refs
    env_vars: list = field(default_factory=list)           # SPRING_PROFILES_ACTIVE, JAVA_OPTS, etc.


@dataclass
class CrawlIndex:
    schema_version: int
    scan: dict
    stats: dict
    warnings: list
    java_classes: list           # list[JavaClass]
    xml_signals: list            # list[XmlSignal]
    config_signals: list         # list[ConfigSignal]
    sql_signals: list = field(default_factory=list)     # list[SqlSignal]
    shell_signals: list = field(default_factory=list)   # list[ShellSignal]


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

def _strip_java_noise(src: str) -> str:
    """Remove block comments, line comments, and string literals from Java source
    before regex parsing. This avoids matching @annotations or method-like
    constructs inside comments or strings."""
    src = RE_BLOCK_COMMENT.sub("", src)
    src = RE_LINE_COMMENT.sub("", src)
    src = RE_STRING_LITERAL.sub('""', src)
    return src


def _split_csv_types(s: str | None) -> list:
    if not s:
        return []
    # Drop generic parameters so "Comparable<Foo>" → "Comparable"
    out = []
    depth = 0
    buf = []
    for ch in s:
        if ch == "<":
            depth += 1
            continue
        if ch == ">":
            depth -= 1
            continue
        if depth > 0:
            # Inside a generic parameter list — strip it entirely so
            # "JpaRepository<FileDeliveryEntity, Long>" → "JpaRepository"
            continue
        if ch == "," and depth == 0:
            piece = "".join(buf).strip()
            if piece:
                out.append(piece)
            buf = []
        else:
            buf.append(ch)
    piece = "".join(buf).strip()
    if piece:
        out.append(piece)
    return out


def _import_tail_tokens(imports: list) -> list:
    """For each import, take its last two dot-segments; dedupe; cap at the limit.
    Example: 'org.springframework.web.bind.annotation.RestController' → 'annotation.RestController'."""
    seen = []
    for imp in imports:
        parts = imp.split(".")
        if len(parts) >= 2:
            tail = ".".join(parts[-2:])
        else:
            tail = imp
        if tail not in seen:
            seen.append(tail)
        if len(seen) >= MAX_IMPORT_TAIL_TOKENS:
            break
    return seen


def _file_is_too_small(path: Path) -> bool:
    try:
        return path.stat().st_size < MIN_FILE_CHARS
    except OSError:
        return True


def _is_generated(raw_src: str) -> bool:
    head = raw_src[:2048]
    return any(m in head for m in GENERATED_MARKERS)


# ─────────────────────────────────────────────────────────────────────────────
# Java parsing
# ─────────────────────────────────────────────────────────────────────────────

def parse_java_file(path: Path, repo_root: Path) -> tuple:
    """
    Parse a single .java file. Returns (java_classes_list, warning_or_none).
    A file with multiple top-level types yields one JavaClass entry per type
    (rare but valid).
    """
    try:
        raw = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return [], f"unreadable: {path} ({e})"

    if len(raw) < MIN_FILE_CHARS:
        return [], None

    file_is_generated = _is_generated(raw)
    if file_is_generated:
        return [], None  # silently skip per spec

    src = _strip_java_noise(raw)
    line_count = raw.count("\n") + 1

    package_match = RE_PACKAGE.search(src)
    package = package_match.group(1) if package_match else None

    imports = [m.group(1) for m in RE_IMPORT.finditer(src)]
    tail = _import_tail_tokens(imports)

    # Annotations file-wide (we only care about first MAX_ANNOTATIONS at top of file)
    annotations = []
    for m in RE_ANNOTATION.finditer(src):
        name = m.group(1)
        if name not in annotations:
            annotations.append(name)
        if len(annotations) >= MAX_ANNOTATIONS:
            break

    method_names = []
    for m in RE_METHOD.finditer(src):
        name = m.group(1)
        # Skip pseudo-method matches that look like control flow
        if name in {"if", "for", "while", "switch", "catch", "return", "synchronized"}:
            continue
        if name not in method_names:
            method_names.append(name)
        if len(method_names) >= MAX_METHOD_NAMES:
            break

    rel_path = path.relative_to(repo_root).as_posix()
    fname = path.name

    # Flags
    base_flags = []
    if RE_DEPRECATED_ANN.search(src) or RE_DEPRECATED_DOC.search(raw):
        base_flags.append("deprecated")
    if line_count > GOD_CLASS_LINES:
        base_flags.append("god_class")
    if RE_TEST_FILENAME.search(fname) or "/test/" in rel_path or "/tests/" in rel_path:
        base_flags.append("test")

    type_matches = list(RE_TYPE_DECL.finditer(src))
    if not type_matches:
        # Probably package-info.java or similar — emit a stub entry so downstream
        # tools know the file existed.
        return [
            JavaClass(
                file_path=rel_path,
                package=package,
                class_name=path.stem,
                type="unknown",
                annotations=annotations,
                method_names=[],
                extends=None,
                implements=[],
                import_tail_tokens=tail,
                line_count=line_count,
                flags=base_flags,
            )
        ], None

    results = []
    for tm in type_matches:
        type_kind = tm.group(1)
        class_name = tm.group(2)
        extends_raw = tm.group(3)
        implements_raw = tm.group(4)
        extends_list = _split_csv_types(extends_raw)
        implements_list = _split_csv_types(implements_raw)
        # For interfaces and records, "extends" can be a comma-separated list.
        # We expose extends as the first one for class/enum, and join all for interface.
        if type_kind == "interface":
            extends_val = ", ".join(extends_list) if extends_list else None
        else:
            extends_val = extends_list[0] if extends_list else None

        results.append(
            JavaClass(
                file_path=rel_path,
                package=package,
                class_name=class_name,
                type=type_kind,
                annotations=annotations,
                method_names=method_names,
                extends=extends_val,
                implements=implements_list,
                import_tail_tokens=tail,
                line_count=line_count,
                flags=list(base_flags),
            )
        )
    return results, None


