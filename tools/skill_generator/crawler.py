"""
Stage 1 crawler for the FeatureBased Skill Generator Agent.

Walks a Java repository, parses .java / .xml / .properties / .yml / .sql / .sh
files locally, and emits a single JSON index. Zero AI calls. Deterministic.

This is the foundation Stage 2 (Plan) and Stage 3 (Generate) feed off. Per the
pipeline spec (AGENT.md and artifact 2), this stage spends no tokens — it's
pure local file parsing.

Public API:
    crawl(repo_root, *, extra_excludes=set(), include_tests=True) -> CrawlIndex

CLI entry point lives in skill_generator.cli; this module can also be run
directly:
    python -m skill_generator.crawler <repo-root>
"""
