# XML parsing
# ─────────────────────────────────────────────────────────────────────────────

def _strip_xml_ns(tag: str) -> str:
    return tag.split("}", 1)[-1] if "}" in tag else tag


def _classify_xml(root: ET.Element, fname: str) -> str:
    tag = _strip_xml_ns(root.tag)
    fname_lower = fname.lower()
    ns = root.tag.split("}", 1)[0].lstrip("{") if "}" in root.tag else ""
    if tag == "web-app" or fname_lower == "web.xml":
        return "web_xml"
    if tag == "struts-config" or "struts" in fname_lower:
        return "struts_config"
    # Spring Batch — looks like <beans> but with a batch namespace, OR a <job> element.
    if "springframework.org/schema/batch" in ns:
        return "spring_batch"
    if tag == "beans":
        # Look for a Spring Batch <job> child to disambiguate.
        for child in root.iter():
            if _strip_xml_ns(child.tag) == "job":
                return "spring_batch"
        return "spring_context"
    if tag == "hibernate-configuration":
        return "hibernate_cfg"
    if tag == "hibernate-mapping" or fname_lower.endswith(".hbm.xml"):
        return "hbm"
    if tag == "persistence" or fname_lower == "persistence.xml":
        return "persistence"
    if "quartz" in fname_lower or tag in {"job-scheduling-data", "quartz"}:
        return "quartz"
    return "unknown"


def parse_xml_file(path: Path, repo_root: Path) -> tuple:
    try:
        raw = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return None, f"unreadable: {path} ({e})"
    if len(raw) < MIN_FILE_CHARS:
        return None, None
    try:
        root = ET.fromstring(raw)
    except ET.ParseError as e:
        return None, f"xml-parse-error: {path} ({e})"

    rel = path.relative_to(repo_root).as_posix()
    xml_type = _classify_xml(root, path.name)
    signals = []

    def iter_all(elem):
        yield elem
        for child in elem:
            yield from iter_all(child)

    if xml_type == "web_xml":
        url_patterns_by_name = {}
        servlet_classes_by_name = {}
        for el in iter_all(root):
            tag = _strip_xml_ns(el.tag)
            if tag == "servlet":
                name = None
                cls = None
                for sub in el:
                    stag = _strip_xml_ns(sub.tag)
                    if stag == "servlet-name":
                        name = (sub.text or "").strip()
                    elif stag == "servlet-class":
                        cls = (sub.text or "").strip()
                if name and cls:
                    servlet_classes_by_name[name] = cls
            elif tag == "servlet-mapping":
                name = None
                url = None
                for sub in el:
                    stag = _strip_xml_ns(sub.tag)
                    if stag == "servlet-name":
                        name = (sub.text or "").strip()
                    elif stag == "url-pattern":
                        url = (sub.text or "").strip()
                if name and url:
                    url_patterns_by_name.setdefault(name, []).append(url)
        for name, cls in servlet_classes_by_name.items():
            for url in url_patterns_by_name.get(name, []):
                signals.append({"kind": "servlet_mapping", "name": name, "url_pattern": url, "class": cls})

    elif xml_type == "struts_config":
        for el in iter_all(root):
            if _strip_xml_ns(el.tag) == "action":
                path_attr = el.attrib.get("path")
                type_attr = el.attrib.get("type")
                if path_attr and type_attr:
                    signals.append({"kind": "struts_action", "path": path_attr, "class": type_attr})

    elif xml_type == "spring_context":
        for el in iter_all(root):
            if _strip_xml_ns(el.tag) == "bean":
                bean_id = el.attrib.get("id") or el.attrib.get("name")
                bean_class = el.attrib.get("class")
                if bean_id and bean_class:
                    signals.append({"kind": "bean", "id": bean_id, "class": bean_class})

    elif xml_type == "hibernate_cfg":
        for el in iter_all(root):
            if _strip_xml_ns(el.tag) == "mapping":
                cls = el.attrib.get("class")
                res = el.attrib.get("resource")
                signals.append({"kind": "hibernate_mapping_ref", "class": cls, "resource": res})

    elif xml_type == "hbm":
        for el in iter_all(root):
            tag = _strip_xml_ns(el.tag)
            if tag in {"class", "subclass", "joined-subclass"}:
                cls = el.attrib.get("name")
                table = el.attrib.get("table")
                if cls:
                    signals.append({"kind": "hibernate_mapping", "class": cls, "table": table})

    elif xml_type == "persistence":
        for el in iter_all(root):
            if _strip_xml_ns(el.tag) == "class":
                cls = (el.text or "").strip()
                if cls:
                    signals.append({"kind": "jpa_entity", "class": cls})

    elif xml_type == "spring_batch":
        for el in iter_all(root):
            tag = _strip_xml_ns(el.tag)
            if tag == "job":
                job_id = el.attrib.get("id")
                if job_id:
                    signals.append({"kind": "batch_job", "id": job_id})
            elif tag == "step":
                step_id = el.attrib.get("id")
                if step_id:
                    signals.append({"kind": "batch_step", "id": step_id})
            elif tag in {"tasklet", "chunk"}:
                ref = el.attrib.get("ref") or el.attrib.get("reader") or el.attrib.get("writer")
                if ref:
                    signals.append({"kind": "batch_component", "tag": tag, "ref": ref})

    elif xml_type == "quartz":
        # Multiple variants: Quartz 1.x job-scheduling-data, Quartz 2.x with <schedule>
        current_job = None
        for el in iter_all(root):
            tag = _strip_xml_ns(el.tag)
            if tag == "job" or tag == "job-detail":
                current_job = {"kind": "quartz_job", "class": None, "name": None, "cron": None}
                for sub in el:
                    stag = _strip_xml_ns(sub.tag)
                    if stag in {"job-class"}:
                        current_job["class"] = (sub.text or "").strip()
                    elif stag in {"name"}:
                        current_job["name"] = (sub.text or "").strip()
                if current_job["class"]:
                    signals.append(dict(current_job))
            elif tag in {"cron", "cron-expression"}:
                cron_val = (el.text or "").strip()
                if signals and signals[-1].get("kind") == "quartz_job":
                    signals[-1]["cron"] = cron_val

    # Skip XML with no useful signals
    if not signals and xml_type == "unknown":
        return None, None
    return XmlSignal(file_path=rel, xml_type=xml_type, signals=signals), None


# ─────────────────────────────────────────────────────────────────────────────
# Properties / YAML parsing
# ─────────────────────────────────────────────────────────────────────────────

def _extract_properties_prefixes(text: str) -> list:
    """Return distinct prefix keys (everything before the first dot or =) that
    match CONFIG_PREFIXES_OF_INTEREST or look meaningful."""
    seen = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("!"):
            continue
        # key=value or key:value
        for sep in ("=", ":"):
            if sep in line:
                key = line.split(sep, 1)[0].strip()
                break
        else:
            continue
        if not key:
            continue
        top = key.split(".", 1)[0]
        prefix_full = ".".join(key.split(".")[:2]) if "." in key else key
        if prefix_full not in seen:
            seen.append(prefix_full)
    return seen


def _extract_yaml_prefixes(text: str) -> list:
    """Return top-level YAML keys plus second-level keys for the most interesting
    prefixes. Implementation is intentionally simple (line-based) — we only need
    prefixes, not values."""
    seen = []
    stack = []   # [(indent, key)]
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        # Pure-YAML lines we care about look like 'key:' or 'key: value'
        indent = len(line) - len(line.lstrip(" "))
        stripped = line.strip()
        if ":" not in stripped:
            continue
        key = stripped.split(":", 1)[0].strip()
        if not key or not re.match(r"^[A-Za-z_][\w.-]*$", key):
            continue
        # Pop deeper or equal indents
        while stack and stack[-1][0] >= indent:
            stack.pop()
        stack.append((indent, key))
        path = ".".join(k for _, k in stack)
        # Keep top-level and second-level prefixes
        if path.count(".") <= 1 and path not in seen:
            seen.append(path)
    return seen


def parse_config_file(path: Path, repo_root: Path) -> tuple:
    try:
        raw = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return None, f"unreadable: {path} ({e})"
    if len(raw) < MIN_FILE_CHARS:
        return None, None
    rel = path.relative_to(repo_root).as_posix()
    suffix = path.suffix.lower()
    if suffix == ".properties":
        prefixes = _extract_properties_prefixes(raw)
        ctype = "properties"
    elif suffix in {".yml", ".yaml"}:
        prefixes = _extract_yaml_prefixes(raw)
        ctype = "yaml"
    else:
        return None, None
    if not prefixes:
        return None, None
    return ConfigSignal(file_path=rel, config_type=ctype, key_prefixes=prefixes), None


# ─────────────────────────────────────────────────────────────────────────────
# SQL parsing — stored procs, DDL, migrations
# ─────────────────────────────────────────────────────────────────────────────

RE_SQL_CREATE_PROC = re.compile(
    r"\bCREATE\s+(?:OR\s+REPLACE\s+)?(?:PROCEDURE|FUNCTION)\s+(?:IF\s+NOT\s+EXISTS\s+)?([\w.`\"]+)",
    re.IGNORECASE,
)
RE_SQL_CREATE_TABLE = re.compile(
    r"\bCREATE\s+(?:TEMPORARY\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([\w.`\"]+)",
    re.IGNORECASE,
)
RE_SQL_CREATE_VIEW = re.compile(
    r"\bCREATE\s+(?:OR\s+REPLACE\s+)?VIEW\s+([\w.`\"]+)",
    re.IGNORECASE,
)
RE_SQL_ALTER_TABLE = re.compile(
    r"\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?([\w.`\"]+)",
    re.IGNORECASE,
)
RE_FLYWAY_NAMING = re.compile(r"^V[\d_]+__\w+\.sql$|^R__\w+\.sql$", re.IGNORECASE)
RE_LIQUIBASE_NAMING = re.compile(r"changelog|changeset", re.IGNORECASE)


def _clean_sql_name(raw: str) -> str:
    return raw.strip("`\"[]").strip()


def parse_sql_file(path: Path, repo_root: Path) -> tuple:
    try:
        raw = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return None, f"unreadable: {path} ({e})"
    if len(raw) < MIN_FILE_CHARS:
        return None, None

    rel = path.relative_to(repo_root).as_posix()
    fname = path.name

    procedures = []
    for m in RE_SQL_CREATE_PROC.finditer(raw):
        name = _clean_sql_name(m.group(1))
        if name and name not in procedures:
            procedures.append(name)
    tables = []
    for m in RE_SQL_CREATE_TABLE.finditer(raw):
        name = _clean_sql_name(m.group(1))
        if name and name not in tables:
            tables.append(name)
    views = []
    for m in RE_SQL_CREATE_VIEW.finditer(raw):
        name = _clean_sql_name(m.group(1))
        if name and name not in views:
            views.append(name)
    altered = []
    for m in RE_SQL_ALTER_TABLE.finditer(raw):
        name = _clean_sql_name(m.group(1))
        if name and name not in altered:
            altered.append(name)

    if not (procedures or tables or views or altered):
        return None, None

    # Classify kind
    if procedures and not tables:
        kind = "stored_proc"
    elif tables and not procedures:
        kind = "ddl"
    elif procedures and tables:
        kind = "mixed"
    elif altered:
        kind = "ddl"
    else:
        kind = "ddl"

    flags = []
    # Flyway / Liquibase naming
    if RE_FLYWAY_NAMING.match(fname):
        flags.append("flyway_migration")
        kind = "migration"
    if "liquibase" in rel.lower() or "changelog" in rel.lower():
        flags.append("liquibase")
        kind = "migration"
    if procedures:
        flags.append("callable_from_java")

    return SqlSignal(
        file_path=rel,
        sql_kind=kind,
        procedures=procedures,
        tables=tables,
        views=views,
        altered_tables=altered,
        flags=flags,
    ), None


# ─────────────────────────────────────────────────────────────────────────────
# Shell-script parsing — invocations, env, SQL hooks
# ─────────────────────────────────────────────────────────────────────────────

RE_SH_JAVA_CLASS = re.compile(r"\bjava\b[^\n]*?\s([\w.]+\.[A-Z]\w+)")
RE_SH_JAR = re.compile(r"\b-jar\s+([\w./-]+\.jar)\b")
RE_SH_PSQL = re.compile(r"\b(?:psql|mysql|sqlplus|sqlcmd|mongo|cqlsh)\b[^\n]*?(?:-f\s+|<\s*)([\w./-]+\.sql)")
RE_SH_ENV_VAR = re.compile(r"\b(SPRING_PROFILES_ACTIVE|JAVA_OPTS|JAVA_HOME|CLASSPATH|MAVEN_OPTS|GRADLE_OPTS|DB_URL|DATABASE_URL)\b")


def parse_shell_file(path: Path, repo_root: Path) -> tuple:
    try:
        raw = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return None, f"unreadable: {path} ({e})"
    if len(raw) < MIN_FILE_CHARS:
        return None, None

    rel = path.relative_to(repo_root).as_posix()

    java_classes_invoked = []
    for m in RE_SH_JAVA_CLASS.finditer(raw):
        cls = m.group(1)
        if cls not in java_classes_invoked:
            java_classes_invoked.append(cls)

    jars = []
    for m in RE_SH_JAR.finditer(raw):
        j = m.group(1)
        if j not in jars:
            jars.append(j)

    sql_invocations = []
    for m in RE_SH_PSQL.finditer(raw):
        sql_invocations.append(m.group(1))

    env_vars = []
    for m in RE_SH_ENV_VAR.finditer(raw):
        v = m.group(1)
        if v not in env_vars:
            env_vars.append(v)

    if not (java_classes_invoked or jars or sql_invocations or env_vars):
        return None, None

    return ShellSignal(
        file_path=rel,
        java_invocations=java_classes_invoked,
        java_jars=jars,
        sql_invocations=sql_invocations,
        env_vars=env_vars,
    ), None


# ─────────────────────────────────────────────────────────────────────────────
# Walker
# ─────────────────────────────────────────────────────────────────────────────

def _iter_files(repo_root: Path, extra_excludes: set) -> Iterable:
    excludes = DEFAULT_EXCLUDE_DIRS | set(extra_excludes)
    for path in repo_root.rglob("*"):
        # Skip excluded directories anywhere in the tree
        parts = set(path.parts)
        if parts & excludes:
            continue
        if not path.is_file():
            continue
        if path.suffix.lower() in BINARY_EXTENSIONS:
            continue
        yield path


def _detect_framework(java_classes: list, xml_signals: list) -> str:
    """Best-effort framework label based on what we found."""
    anns = set()
    for jc in java_classes:
        anns.update(jc.annotations)
    has_spring_boot = "SpringBootApplication" in anns
    has_rest_controller = "RestController" in anns or "Controller" in anns
    has_path = "Path" in anns  # JAX-RS / Quarkus
    has_struts = any(s.xml_type == "struts_config" for s in xml_signals)
    has_spring_xml = any(s.xml_type == "spring_context" for s in xml_signals)
    has_hibernate_cfg = any(s.xml_type in {"hibernate_cfg", "hbm"} for s in xml_signals)
    has_web_xml = any(s.xml_type == "web_xml" for s in xml_signals)

    if has_spring_boot:
        return "Spring Boot"
    if has_path and not has_rest_controller:
        return "Quarkus"
    if has_struts:
        return "Struts"
    if has_rest_controller and (has_spring_xml or not has_web_xml):
        return "Spring MVC"
    if has_hibernate_cfg and has_web_xml:
        return "Spring MVC (legacy)"
    if has_web_xml and not has_rest_controller:
        return "Raw Servlet"
    return "Unknown"


def _detect_build_system(repo_root: Path) -> str:
    if (repo_root / "pom.xml").exists():
        return "Maven"
    if (repo_root / "build.gradle").exists() or (repo_root / "build.gradle.kts").exists():
        return "Gradle"
    if (repo_root / "build.xml").exists():
        return "Ant"
    return "Unknown"


def _normalize_java_version(raw: str) -> str:
    """Map '1.8' to '8', strip JavaVersion.VERSION_17 prefix, etc."""
    raw = raw.strip().lstrip("v").lstrip("V")
    if raw.startswith("VERSION_"):
        raw = raw[len("VERSION_"):]
    if "." in raw:
        major, minor = raw.split(".", 1)
        if major == "1":
            return minor
        return major
    return raw


def _detect_java_version(repo_root: Path) -> str:
    pom = repo_root / "pom.xml"
    if pom.exists():
        try:
            raw = pom.read_text(encoding="utf-8", errors="replace")
        except OSError:
            raw = ""
        m = re.search(
            r"<(?:maven\.compiler\.)?(?:source|target|release)>\s*([\d.]+)\s*</",
            raw,
        )
        if m:
            return _normalize_java_version(m.group(1))
    # Gradle (build.gradle or build.gradle.kts)
    for gradle_file in ("build.gradle", "build.gradle.kts"):
        gf = repo_root / gradle_file
        if gf.exists():
            try:
                raw = gf.read_text(encoding="utf-8", errors="replace")
                m = re.search(
                    r"(?:sourceCompatibility|targetCompatibility|jvmTarget)\s*=?\s*['\"]?"
                    r"(?:JavaVersion\.)?([\w.]+)",
                    raw,
                )
                if m:
                    return _normalize_java_version(m.group(1))
            except OSError:
                pass
    return "Unknown"


